def verify_duplicate_collection(page):
    page.locator('#home').click()
    expect(page.locator('#overview')).to_be_visible()
    task = dict(id=1, platform='bilibili', mode='topic', query='重复采集回归', limit=3,
                minutes=0, status='completed', last_run_id=42, run_id=42)
    page.route('**/collection-tasks?*', lambda route: route.fulfill(json={'tasks': [task], 'platforms': [], 'offset': 0, 'total': 1}))

    def repeat(route):
        task['run_id'] = None
        route.fulfill(json={'added': 0, 'updated': 0, 'duplicates': 3, 'run_id': None})

    page.route('**/collection-tasks/1/run', repeat)
    page.locator('#channelNav').click()
    result = page.locator('#taskList').get_by_role('button', name='查看采集结果')
    expect(result).to_be_visible()
    page.locator('#taskList').get_by_role('button', name='立即采集').click()
    expect(page.locator('#taskNotice')).to_contain_text('跳过重复 3 条')
    expect(page.locator('#taskNotice')).to_contain_text('本次未生成新批次')
    expect(result).to_have_count(0)
    page.locator('#refreshTasks').click()
    expect(result).to_have_count(0)


def check_form_layout(page):
    viewport=page.viewport_size
    for width in (320,390,768,1179,1180,1440):
        page.set_viewport_size({'width':width,'height':820})
        failures=page.evaluate('''() => [...document.querySelectorAll('.stageMain input,.stageMain .dm-select__button')].flatMap(node=>{
          if(node.matches('[type=hidden],[type=checkbox],[type=radio],.dm-select__native'))return [];
          const r=node.getBoundingClientRect();if(!r.width||!r.height)return [];
          return Math.abs(r.height-44)>1||r.x<-.5||r.right>innerWidth+.5 ? [{field:node.name||node.id||node.textContent.slice(0,30),height:r.height,left:r.x,right:r.right}]:[];
        })''')
        assert not failures,{'width':width,'fields':failures}
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'form overflow {width}'
    page.set_viewport_size(viewport)


